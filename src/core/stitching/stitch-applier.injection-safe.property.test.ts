/**
 * Printable fragments that are notorious for breaking string-concatenated SQL:
 * quote characters, statement terminators, comment markers, and SQL keywords.
 * (No NUL byte — the documented DuckDB-WASM MVP quirk crashes on it, and a
 * literal NUL is not what "injection-safe SQL generation" is about.)
 */
const INJECTION_FRAGMENTS = [
  `'`,
  `"`,
  `''`,
  `""`,
  `';`,
  `";`,
  `');`,
  `");`,
  `--`,
  `/*`,
  `*/`,
  `;`,
  "`",
  `\\`,
  `%`,
  `DROP TABLE sentinel`,
  `'; DROP TABLE sentinel; --`,
  `" ; DROP TABLE "sentinel`,
  `SELECT`,
  `DROP`,
  `' OR '1'='1`,
  `' OR 1=1 --`,
  `O'Brien`,
  `"Night" Howler`,
  `1); DROP TABLE sentinel; --`,
  `résumé`,
  `名字`,
  `🧟`,
  ` `,
];

/** An arbitrary adversarial string: a shuffle/join of injection fragments and noise. */
const adversarialArb: fc.Arbitrary<string> = fc
  .array(
    fc.oneof(
      { weight: 3, arbitrary: fc.constantFrom(...INJECTION_FRAGMENTS) },
      { weight: 1, arbitrary: fc.string({ minLength: 0, maxLength: 4 }) },
    ),
    { minLength: 1, maxLength: 5 },
  )
  .map((parts) => parts.join(""));

/** Like {@link adversarialArb} but guaranteed non-empty and newline-free (a usable identifier/value). */
const adversarialNameArb: fc.Arbitrary<string> = adversarialArb
  .map((s) => s.replace(/[\r\n]/g, " "))
  .filter((s) => s.length > 0);

// ---------------------------------------------------------------------------
// Escaping primitives used by the "no breakout" assertions
// ---------------------------------------------------------------------------

/**
 * Single-pass SQL tokenizer that walks `sql` the way a SQL lexer would,
 * tracking whether it is inside a double-quoted identifier or a single-quoted
 * literal and treating a doubled quote (`""` / `''`) as an escaped quote that
 * stays inside the current span rather than closing it. It returns the text
 * that lies OUTSIDE every well-formed quoted span.
 *
 * Doing both quote kinds in one pass is essential: a `'` inside a double-quoted
 * identifier (e.g. `"stitch_7_clean_'"`) is harmless data, and only a combined
 * scanner that is already "inside an identifier" knows to ignore it. Stripping
 * the two quote kinds independently would mis-flag such a quote as a breakout.
 *
 * If a span is never closed (an odd/unbalanced quote — a real breakout), the
 * opening quote character is emitted into the OUTSIDE text so the caller's
 * assertions catch it.
 */
function textOutsideQuotedSpans(sql: string): string {
  let out = "";
  let i = 0;
  const n = sql.length;
  while (i < n) {
    const ch = sql[i];
    if (ch === '"' || ch === "'") {
      // Enter a quoted span; scan to its matching close, honoring doubling.
      const quote = ch;
      let j = i + 1;
      let closed = false;
      while (j < n) {
        if (sql[j] === quote) {
          if (sql[j + 1] === quote) {
            // Doubled quote → escaped, stays inside the span.
            j += 2;
            continue;
          }
          // Lone quote → closes the span.
          closed = true;
          j += 1;
          break;
        }
        j += 1;
      }
      if (!closed) {
        // Unbalanced opening quote — a genuine breakout. Surface it.
        out += quote;
        i += 1;
      } else {
        i = j;
      }
    } else {
      out += ch;
      i += 1;
    }
  }
  return out;
}

/**
 * Assert that `sql` has NO quote breakout: the text lying outside every
 * well-formed quoted span contains no stray `"` or `'`. A breakout (an
 * unbalanced or un-doubled quote injected by an adversarial name/value) would
 * leave an orphan quote in the outside text.
 */
function expectNoQuoteBreakout(sql: string): void {
  const outside = textOutsideQuotedSpans(sql);
  expect(outside).not.toContain('"');
  expect(outside).not.toContain("'");
}

// ===========================================================================
// Angle 1 — escaping helpers over arbitrary strings
// ===========================================================================

describe("Property 13: quoteIdent / quoteString escaping invariants", () => {
  it("quoteIdent wraps in double quotes and doubles every embedded double quote", () => {
    fc.assert(
      fc.property(adversarialArb, (raw) => {
        const quoted = quoteIdent(raw);
        // Wrapped.
        expect(quoted.startsWith('"')).toBe(true);
        expect(quoted.endsWith('"')).toBe(true);
        // Interior is the input with every " doubled.
        const interior = quoted.slice(1, -1);
        expect(interior).toBe(raw.replace(/"/g, '""'));
        // Every interior double quote is part of a doubled pair: counting "
        // in the interior yields an even number (each original " became "").
        const interiorQuotes = (interior.match(/"/g) ?? []).length;
        expect(interiorQuotes % 2).toBe(0);
        // Round-trip: un-doubling the interior recovers the original name.
        expect(interior.replace(/""/g, '"')).toBe(raw);
        // The whole token is a single balanced identifier (no breakout).
        expectNoQuoteBreakout(quoted);
      }),
      { numRuns: 200 },
    );
  });

  it("quoteString wraps in single quotes and doubles every embedded single quote", () => {
    fc.assert(
      fc.property(adversarialArb, (raw) => {
        const quoted = quoteString(raw);
        expect(quoted.startsWith("'")).toBe(true);
        expect(quoted.endsWith("'")).toBe(true);
        const interior = quoted.slice(1, -1);
        expect(interior).toBe(raw.replace(/'/g, "''"));
        const interiorQuotes = (interior.match(/'/g) ?? []).length;
        expect(interiorQuotes % 2).toBe(0);
        expect(interior.replace(/''/g, "'")).toBe(raw);
        expectNoQuoteBreakout(quoted);
      }),
      { numRuns: 200 },
    );
  });
});

