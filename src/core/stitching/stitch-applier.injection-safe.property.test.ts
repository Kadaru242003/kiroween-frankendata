/**
 * Property 13 — Generated SQL is injection-safe under adversarial values.
 *
 * Feature: frankendata-ai-stitching, Design Property 13 ("Generated SQL is
 * injection-safe under adversarial values", design: "Table naming convention" →
 * "Identifier and literal escaping").
 *
 * **Validates: Requirements 4.1, 2.x (escaping), Named-constants escaping
 * invariant** (every identifier via `quoteIdent`, every literal via
 * `quoteString`).
 *
 * Property 13 statement: for ANY user-edited canonical value or sampled value —
 * including ones containing single/double quotes, SQL keywords (`SELECT`,
 * `DROP TABLE`), semicolons, comment markers (`--`, `/* *\/`), backticks, or
 * unicode — the SQL generated by `StitchApplier` (cleaned copies, `CASE` maps,
 * join keys) runs without error and treats the value purely as data: originals
 * (and a planted `sentinel` table) are untouched, and the value round-trips
 * through the cleaned table unchanged. No adversarial input can break out of
 * its identifier/literal context.
 *
 * This file proves the invariant from THREE angles, all at ≥ 100 fast-check
 * iterations in a dedicated file (the project convention):
 *
 *   1. **Escaping helpers** — {@link quoteIdent} / {@link quoteString} over
 *      arbitrary strings always wrap the input and double every embedded quote,
 *      producing balanced, single-token-safe SQL with no unescaped breakout.
 *   2. **Pure SQL builders** — {@link buildCleanedCopySql} /
 *      {@link buildJoinChainSql} over adversarial table names, column names, and
 *      canonical/variant literals: every adversarial lexeme appears ONLY inside
 *      a properly-escaped identifier or literal; stripping out those escaped
 *      spans leaves SQL with no stray quote and no injected keyword.
 *   3. **DuckDB-backed (node-blocking MVP)** — plant a `sentinel` table, run a
 *      real apply whose table/column names and category-standardize canonical
 *      values are adversarial injection payloads, and assert: the `sentinel`
 *      survives (no injected DROP/statement executed), apply either succeeds or
 *      fails safely without executing injected SQL, and the adversarial value
 *      round-trips through the cleaned copy unchanged.
 *
 * ## Environment note (same pattern as the other applier DuckDB tests)
 *
 * DuckDB-WASM's browser bundles need a browser worker unavailable under Vitest's
 * jsdom runner, so the backed angle wraps the *node-blocking* MVP bundle in a
 * {@link DuckDBConnectionAdapter} and injects it via {@link createDuckDBService}.
 * A FRESH in-memory DuckDB is created per property iteration and disposed after
 * it, so the MVP bundle never carries a bad `_setThrew` state between
 * iterations (observed when an apply SQL throws mid-run and the same instance is
 * reused). We follow the documented MVP quirk and never put a literal NUL byte
 * in a value — adversarial payloads use printable characters only.
 */

