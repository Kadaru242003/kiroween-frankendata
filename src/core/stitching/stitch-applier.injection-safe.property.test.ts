describe("Property 13: pure SQL builders escape all adversarial names and values", () => {
  it("buildCleanedCopySql keeps adversarial table/column names + CASE literals inside escaped spans", () => {
    fc.assert(
      fc.property(
        adversarialNameArb, // source table name
        adversarialNameArb, // source column name
        adversarialArb, // category variant surface form
        adversarialArb, // (possibly user-edited) canonical value
        (tableName, columnName, variant, canonical) => {
          const schema: ColumnSchema[] = [{ name: columnName, type: "string" }];
          const proposal: CleaningProposal = {
            id: "cat:x",
            target: { tableName, columnName },
            kind: "category-standardize",
            before: variant,
            after: canonical,
            reason: "standardize",
            canonical,
            variantMap: { [variant]: canonical },
          };
          const approved: ApprovedCleaning = {
            columnProposals: [proposal],
            outlierColumns: [],
            dedupe: false,
          };

          const { createSql, insertSql } = buildCleanedCopySql(
            7,
            tableName,
            schema,
            approved,
          );

          for (const sql of [createSql, insertSql]) {
            // No quote breakout: strip escaped idents/literals → no stray quote.
            expectNoQuoteBreakout(sql);

            // The adversarial identifiers/literals appear ONLY through the
            // escaping helpers — outside every well-formed quoted span, no raw
            // single/double quote survives, so no adversarial value can break
            // out of its identifier/literal context.
            const outside = textOutsideQuotedSpans(sql);
            expect(outside).not.toContain('"');
            expect(outside).not.toContain("'");
          }

          // The escaped literal forms are literally present in the INSERT.
          expect(insertSql).toContain(quoteString(variant));
          expect(insertSql).toContain(quoteString(canonical));
          // The escaped identifier forms are present too.
          expect(insertSql).toContain(quoteIdent(columnName));
          expect(createSql).toContain(quoteIdent(columnName));
        },
      ),
      { numRuns: 150 },
    );
  });

  it("buildJoinChainSql keeps adversarial table/column names inside escaped identifier spans", () => {
    fc.assert(
      fc.property(
        adversarialNameArb,
        adversarialNameArb,
        adversarialNameArb,
        adversarialNameArb,
        (tableA, tableB, colA, colB) => {
          // Two distinct logical tables (dedupe names if the generator collides).
          const nameA = tableA;
          const nameB = tableA === tableB ? tableB + "_2" : tableB;

          const tables: JoinTableInput[] = [
            {
              tableName: nameA,
              readTableName: nameA,
              schema: [{ name: colA, type: "string" }],
              rowCount: 3,
            },
            {
              tableName: nameB,
              readTableName: nameB,
              schema: [{ name: colB, type: "string" }],
              rowCount: 2,
            },
          ];
          const ref = (t: string, c: string): ColumnRef => ({
            tableName: t,
            columnName: c,
            type: "string",
          });
          const match: MatchProposal = {
            id: "m:1",
            left: ref(nameA, colA),
            right: ref(nameB, colB),
            confidence: 0.9,
            reason: "match",
            source: "rules",
            components: { nameSim: 0.9, typeCompat: 1, valueOverlap: 0.9 },
          };

          const { createSql } = buildJoinChainSql(4, tables, [match]);
          expectNoQuoteBreakout(createSql);
          const outside = textOutsideQuotedSpans(createSql);
          expect(outside).not.toContain('"');
          expect(outside).not.toContain("'");
          // The adversarial identifiers are present only via quoteIdent.
          expect(createSql).toContain(quoteIdent(nameA));
          expect(createSql).toContain(quoteIdent(nameB));
          expect(createSql).toContain(quoteIdent(colA));
          expect(createSql).toContain(quoteIdent(colB));
        },
      ),
      { numRuns: 150 },
    );
  });
});

