const require = createRequire(import.meta.url);

// eslint-disable-next-line @typescript-eslint/no-var-requires
const duckdb = require("@duckdb/duckdb-wasm/dist/duckdb-node-blocking.cjs") as {
  createDuckDB: (
    bundles: unknown,
    logger: unknown,
    runtime: unknown,
  ) => Promise<DuckDBNodeInstance>;
  NODE_RUNTIME: unknown;
  VoidLogger: new () => unknown;
  DuckDBAccessMode: { READ_WRITE: number };
};

interface DuckDBConnectionLike {
  query(text: string): { toArray(): Array<{ toJSON(): Record<string, unknown> }> };
  close(): void;
}

interface DuckDBNodeInstance {
  instantiate(): Promise<unknown>;
  open(config: { path?: string; accessMode?: number }): void;
  connect(): DuckDBConnectionLike;
  reset(): void;
}

const DUCKDB_DIST = path.dirname(
  require.resolve("@duckdb/duckdb-wasm/dist/duckdb-node-blocking.cjs"),
);

const bundles = {
  mvp: {
    mainModule: path.join(DUCKDB_DIST, "duckdb-mvp.wasm"),
    mainWorker: path.join(DUCKDB_DIST, "duckdb-node-mvp.worker.cjs"),
  },
};

/** A FRESH in-memory node-blocking adapter + its disposer (one per iteration). */
async function createNodeAdapter(): Promise<{
  adapter: DuckDBConnectionAdapter;
  dispose: () => void;
}> {
  const db = await duckdb.createDuckDB(
    bundles,
    new duckdb.VoidLogger(),
    duckdb.NODE_RUNTIME,
  );
  await db.instantiate();
  db.open({ path: ":memory:", accessMode: duckdb.DuckDBAccessMode.READ_WRITE });
  const conn = db.connect();
  const adapter: DuckDBConnectionAdapter = {
    async run(sql: string) {
      return conn.query(sql).toArray().map((r) => r.toJSON());
    },
  };
  return {
    adapter,
    dispose: () => {
      conn.close();
      db.reset();
    },
  };
}

/** The planted table an injection would try to drop. Fixed, un-prefixed name. */
const SENTINEL = "sentinel";

/**
 * The Feature-1 NullToken set (`src/core/predicates.ts`): `null`, empty/
 * whitespace-only, and the texts `n/a` / `na` / `null` / `-` (case-insensitive,
 * trimmed) are stored by {@link createDuckDBService} as SQL NULL. A value we
 * want to observe round-tripping through the cleaned copy must NOT be one of
 * these, else it comes back NULL for reasons unrelated to escaping.
 */
function isNullTokenish(value: string): boolean {
  const trimmed = value.trim();
  if (trimmed === "") {
    return true;
  }
  return new Set(["n/a", "na", "null", "-"]).has(trimmed.toLowerCase());
}

/**
 * Adversarial payloads safe to feed through the WHOLE DuckDB apply path. These
 * exercise injection via DATA: a category-standardize canonical value and the
 * variant it maps. Printable only (no NUL byte, per the MVP quirk).
 */
const backedPayloadArb: fc.Arbitrary<string> = fc
  .oneof(
    fc.constantFrom(
      `'; DROP TABLE ${SENTINEL}; --`,
      `'); DROP TABLE ${SENTINEL}; --`,
      `' OR '1'='1`,
      `O'Brien`,
      `"Night" Howler`,
      `label; DROP TABLE ${SENTINEL}`,
      `a'--`,
      `SELECT * FROM ${SENTINEL}`,
      `résumé`,
      `名字🧟`,
    ),
    adversarialNameArb,
  )
  .map((s) => s.replace(/[\r\n]/g, " "))
  .filter((s) => s.length > 0 && !s.includes("\u0000"));

/**
 * An adversarial payload that is also a storable DATA value — i.e. not a
 * NullToken — so it survives insertion and can be observed round-tripping
 * through the cleaned copy unchanged. (NullToken-ish payloads are still
 * exercised as table/column NAMES above; this is only for the variant/canonical
 * cell values whose round-trip we assert.)
 */
const backedDataValueArb: fc.Arbitrary<string> = backedPayloadArb.filter(
  (s) => !isNullTokenish(s),
);

function loaded(
  tableName: string,
  schema: ColumnSchema[],
  rowCount: number,
): LoadedTable {
  return {
    loadId: 0,
    tableName,
    sourceFileName: tableName,
    schema,
    rowCount,
  };
}

describe("Property 13: DuckDB-backed — sentinel survives any injection payload", () => {
  it("runs apply with adversarial names/values without executing injected SQL; sentinel survives and the value round-trips", async () => {
    await fc.assert(
      fc.asyncProperty(
        // Adversarial logical table names, column names, and a category value.
        backedPayloadArb, // table A logical/physical name
        backedPayloadArb, // table B logical/physical name
        backedPayloadArb, // the shared key column name (same on both tables)
        backedDataValueArb, // a category variant surface form present in data
        backedDataValueArb, // the (user-edited) canonical value it maps to
        async (rawTableA, rawTableB, rawKeyCol, variant, canonical) => {
          // Keep the two table names distinct and the key column present in both.
          const tableA = rawTableA;
          const tableB = rawTableA === rawTableB ? rawTableB + " B" : rawTableB;
          const keyCol = rawKeyCol;

          const { adapter, dispose } = await createNodeAdapter();
          try {
            const service = createDuckDBService(adapter);
            await service.init();

            // Plant the sentinel with a known row. An injected DROP/mutation
            // would make it vanish or change; it must survive untouched.
            await service.createTable(
              SENTINEL,
              [{ name: "id", type: "string" }],
              [["alive"]],
            );

            // Two source tables whose key column holds the adversarial `variant`
            // value (so the category-standardize CASE map and the join key both
            // carry the payload through generated SQL).
            const schemaA: ColumnSchema[] = [{ name: keyCol, type: "string" }];
            const schemaB: ColumnSchema[] = [{ name: keyCol, type: "string" }];
            const ltA = await service.createTable(tableA, schemaA, [
              [variant],
              [canonical],
            ]);
            const ltB = await service.createTable(tableB, schemaB, [[variant]]);

            const loadedTables: LoadedTable[] = [
              loaded(tableA, schemaA, ltA.rowCount),
              loaded(tableB, schemaB, ltB.rowCount),
            ];

            // A plan that standardizes the key column on table A to `canonical`
            // (the adversarial literal flows into a CASE map), and matches the
            // two tables on the adversarial key column (the payload flows into
            // identifiers + the join ON clause).
            const cleaning: CleaningProposal = {
              id: "cat:a",
              target: { tableName: tableA, columnName: keyCol },
              kind: "category-standardize",
              before: variant,
              after: canonical,
              reason: "standardize",
              canonical,
              variantMap: { [variant]: canonical },
            };
            const ref = (t: string, c: string): ColumnRef => ({
              tableName: t,
              columnName: c,
              type: "string",
            });
            const match: MatchProposal = {
              id: "m:a-b",
              left: ref(tableA, keyCol),
              right: ref(tableB, keyCol),
              confidence: 0.9,
              reason: "match",
              source: "rules",
              components: { nameSim: 0.9, typeCompat: 1, valueOverlap: 0.9 },
            };
            const plan: StitchPlan = {
              anchorTableName: tableA,
              joinKeysByPair: {},
              approvedMatches: [match],
              approvedCleanings: [cleaning],
            };

            const applier = createStitchApplier(service);

            // Apply must either succeed, or fail SAFELY (a thrown error), but it
            // must NEVER execute an injected statement. We tolerate a throw and
            // assert the sentinel is intact regardless.
            let applyOk = true;
            try {
              await applier.apply(plan, loadedTables);
            } catch {
              applyOk = false;
            }

            // The sentinel table still exists with its original single row —
            // no injected DROP/DELETE/UPDATE ran.
            const sentinelRows = await service.query<{ n: number }>(
              `SELECT COUNT(*) AS n FROM ${quoteIdent(SENTINEL)}`,
            );
            expect(Number(sentinelRows[0]?.n)).toBe(1);
            const sentinelVal = await service.query<{ id: string }>(
              `SELECT id FROM ${quoteIdent(SENTINEL)}`,
            );
            expect(sentinelVal[0]?.id).toBe("alive");

            // When apply succeeded, the adversarial canonical value round-trips
            // through the cleaned copy unchanged (it was treated as pure data):
            // table A's variant row was standardized to `canonical`.
            if (applyOk) {
              const cleanName = `stitch_1_clean_${tableA}`;
              const cleaned = await service.query<{ v: string | null }>(
                `SELECT ${quoteIdent(keyCol)} AS v FROM ${quoteIdent(cleanName)}`,
              );
              const values = cleaned.map((r) => r.v);
              // Every original `variant` cell became `canonical`; no cell holds
              // the raw payload as executed SQL (it is stored verbatim as data).
              // Both source rows (variant, canonical) end up as `canonical`.
              for (const v of values) {
                expect(v).toBe(canonical);
              }
            }
          } finally {
            dispose();
          }
        },
      ),
      { numRuns: 100 },
    );
  }, 600_000);
});
